"""Writes runtime/portable/xiv_monster_moves_table.h from XIVLegacy's own server data.

  python3 tools/monster_moves.py <xivlegacy-server>/common/sql/data/server_battle_commands.sql

Each monster move (battle command ids 23000-23999) with its kind from the server's columns:
actionType (1 physical, 2 magic) and actionProperty (the damage kind or element). The runtime picks a
hotbar icon by kind (xiv_monster_moves.c). Nothing here comes from the game's files."""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(sql_path):
    text = open(sql_path, encoding='utf-8').read()
    head = re.search(r'INSERT INTO `server_battle_commands` \(([^)]*)\)', text)
    if not head:
        raise SystemExit('%s: no server_battle_commands insert' % sql_path)
    cols = [c.strip(' `') for c in head.group(1).split(',')]
    at, prop = cols.index('actionType'), cols.index('actionProperty')
    moves = []
    for row in re.finditer(r"^\((\d+), '[^']*', (.*)\),?;?$", text, re.M):
        cid = int(row.group(1))
        if not 23000 <= cid <= 23999:
            continue
        vals = [v.strip() for v in row.group(2).split(',')]
        moves.append((cid, int(vals[at - 2]), int(vals[prop - 2])))
    moves.sort()
    out = ['/* generated by tools/monster_moves.py from server_battle_commands.sql - do not edit */',
           '/* monster move id, actionType (1 physical, 2 magic), actionProperty (damage kind or element) */',
           'static const struct { uint16_t id; uint8_t type, prop; } MONSTER_MOVES[] = {']
    line = ''
    for cid, t, p in moves:
        item = '{%d,%d,%d},' % (cid, t, p)
        if len(line) + len(item) > 110:
            out.append('    ' + line.rstrip())
            line = ''
        line += item + ' '
    if line:
        out.append('    ' + line.rstrip())
    out.append('};')
    dst = os.path.join(ROOT, 'runtime', 'portable', 'xiv_monster_moves_table.h')
    open(dst, 'w').write('\n'.join(out) + '\n')
    print('%s: %d moves' % (dst, len(moves)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
